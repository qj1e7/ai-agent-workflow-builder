"""Rebuilds the sprint evidence from GitHub: pull requests and issues, counted per 2-week sprint.

Writes docs/evidence/fyp/sprint-data.md. Sprint 1 starts on Monday 7 Sep 2026, the first day of
project conduct in the school's schedule, and each sprint is 14 days. Days are Singapore days.
Needs the gh CLI, signed in. Run from the repo root:

    python3 scripts/sprint-stats.py [--as-of YYYY-MM-DD]
"""

import argparse
import datetime as dt
import json
import pathlib
import re
import subprocess
from collections import Counter

FIRST_DAY = dt.date(2026, 9, 7)
SPRINT_DAYS = 14
SGT = dt.timezone(dt.timedelta(hours=8))
SCOPES = ("builder", "runtime", "orchestration", "monitoring", "infra", "ci", "docs")
OUT = pathlib.Path("docs/evidence/fyp/sprint-data.md")
REPO_URL = "https://github.com/qj1e7/ai-agent-workflow-builder"


def gh(kind: str, fields: str) -> list[dict]:
    raw = subprocess.run(
        ["gh", kind, "list", "--state", "all", "--limit", "1000", "--json", fields],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(raw)


def day(stamp: str | None) -> dt.date | None:
    if not stamp:
        return None
    return dt.datetime.fromisoformat(stamp.replace("Z", "+00:00")).astimezone(SGT).date()


def sprint_of(d: dt.date) -> int:
    return (d - FIRST_DAY).days // SPRINT_DAYS + 1


def sprint_dates(n: int) -> tuple[dt.date, dt.date]:
    start = FIRST_DAY + dt.timedelta(days=SPRINT_DAYS * (n - 1))
    return start, start + dt.timedelta(days=SPRINT_DAYS - 1)


def scope_of(title: str) -> str:
    match = re.match(r"^\w+\(([a-z-]+)\)", title)
    return match.group(1) if match and match.group(1) in SCOPES else "other"


def fmt(d: dt.date) -> str:
    return f"{d.day} {d:%b}"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--as-of", type=dt.date.fromisoformat, default=dt.datetime.now(SGT).date())
    as_of = parser.parse_args().as_of

    prs = [p for p in gh("pr", "number,title,state,createdAt,mergedAt,author") if day(p["createdAt"]) <= as_of]
    issues = [i for i in gh("issue", "number,title,state,createdAt,closedAt") if day(i["createdAt"]) <= as_of]
    merged = [p for p in prs if p["mergedAt"] and day(p["mergedAt"]) <= as_of]
    closed_on = {i["number"]: day(i["closedAt"]) for i in issues}

    def open_issues_at(d: dt.date) -> int:
        return sum(1 for i in issues if day(i["createdAt"]) <= d and not (closed_on[i["number"]] and closed_on[i["number"]] <= d))

    last = sprint_of(as_of)
    lines = [
        "# Sprint data, rebuilt from GitHub",
        "",
        f"Generated by `python3 scripts/sprint-stats.py --as-of {as_of}`. Do not edit it by hand. Run the script again instead.",
        f"It counts the pull requests and issues of [{REPO_URL.removeprefix('https://github.com/')}]({REPO_URL}) up to the end of {fmt(as_of)} {as_of.year}, Singapore time.",
        f"Sprints are 14-day blocks from Monday {fmt(FIRST_DAY)} {FIRST_DAY.year}. Sprint {last} is still running on that day, so its numbers are partial.",
        "",
        "## Per sprint",
        "",
        "| Sprint | Dates | PRs merged | " + " | ".join(SCOPES) + " | other | Issues opened | Issues closed | Issues open at the end |",
        "|---|---|---|" + "---|" * len(SCOPES) + "---|---|---|---|",
    ]
    for n in range(1, last + 1):
        start, end = sprint_dates(n)
        in_sprint = [p for p in merged if sprint_of(day(p["mergedAt"])) == n]
        by_scope = Counter(scope_of(p["title"]) for p in in_sprint)
        opened = sum(1 for i in issues if sprint_of(day(i["createdAt"])) == n)
        closed = sum(1 for i in issues if closed_on[i["number"]] and sprint_of(closed_on[i["number"]]) == n)
        cells = [str(by_scope[s]) for s in (*SCOPES, "other")]
        lines.append(
            f"| {n} | {fmt(start)} to {fmt(end)} | {len(in_sprint)} | " + " | ".join(cells)
            + f" | {opened} | {closed} | {open_issues_at(min(end, as_of))} |"
        )

    authors = Counter(p["author"]["login"] for p in merged)
    lines += [
        "",
        f"Merged pull requests by author: " + ", ".join(f"`{a}` {c}" for a, c in authors.most_common()) + ".",
        f"Pull requests still open: {sum(1 for p in prs if p['state'] == 'OPEN')}. Issues still open: {open_issues_at(as_of)}.",
        "",
        "## Pull requests merged per week",
        "",
        "Weeks start on Monday. A chart with one series, so it needs no legend.",
        "",
    ]
    first_week = min(day(p["mergedAt"]) for p in merged)
    first_week -= dt.timedelta(days=first_week.weekday())
    weeks = []
    w = first_week
    while w <= as_of:
        weeks.append((w, sum(1 for p in merged if w <= day(p["mergedAt"]) < w + dt.timedelta(days=7))))
        w += dt.timedelta(days=7)
    top = max(c for _, c in weeks)
    lines += [
        "```mermaid",
        "xychart-beta",
        '    title "Pull requests merged per week"',
        "    x-axis [" + ", ".join(f'"{fmt(w)}"' for w, _ in weeks) + "]",
        f'    y-axis "Merged pull requests" 0 --> {top + 10 - top % 10}',
        "    bar [" + ", ".join(str(c) for _, c in weeks) + "]",
        "```",
        "",
        "| Week starting | Merged |",
        "|---|---|",
        *[f"| {fmt(w)} | {c} |" for w, c in weeks],
        "",
    ]

    start, end = sprint_dates(last)
    days = [start + dt.timedelta(days=k) for k in range((min(end, as_of) - start).days + 1)]
    at_start = open_issues_at(start - dt.timedelta(days=1))
    scope = at_start + sum(1 for i in issues if start <= day(i["createdAt"]) <= end)
    remaining = [open_issues_at(d) for d in days]
    top = max([scope, *remaining])
    lines += [
        f"## Burndown of sprint {last}: open issues at the end of each day",
        "",
        f"The sprint backlog is the issues open when sprint {last} began ({at_start}) plus the issues opened during it, {scope} in all so far.",
        "The line is the issues still open at the end of each day. A new issue lifts the line, a closed one lowers it.",
        "",
        "```mermaid",
        "xychart-beta",
        f'    title "Sprint {last}: issues still open"',
        "    x-axis [" + ", ".join(f'"{fmt(d)}"' for d in days) + "]",
        f'    y-axis "Open issues" 0 --> {top + 5 - top % 5}',
        "    line [" + ", ".join(str(r) for r in remaining) + "]",
        "```",
        "",
        "| Day | Opened that day | Closed that day | Open at the end of the day |",
        "|---|---|---|---|",
    ]
    for d, r in zip(days, remaining):
        o = sum(1 for i in issues if day(i["createdAt"]) == d)
        c = sum(1 for i in issues if closed_on[i["number"]] == d)
        lines.append(f"| {fmt(d)} | {o} | {c} | {r} |")

    lines += ["", "## What each sprint merged", "", "Each list is the sprint's merged pull requests, oldest first. This is the closest record of each sprint backlog that git holds.", ""]
    for n in range(1, last + 1):
        in_sprint = sorted((p for p in merged if sprint_of(day(p["mergedAt"])) == n), key=lambda p: (p["mergedAt"], p["number"]))
        if not in_sprint:
            continue
        s, e = sprint_dates(n)
        lines += [f"<details><summary>Sprint {n}, {fmt(s)} to {fmt(e)}: {len(in_sprint)} pull requests</summary>", ""]
        lines += [f"- {fmt(day(p['mergedAt']))}, [#{p['number']}]({REPO_URL}/pull/{p['number']}) {p['title']}" for p in in_sprint]
        lines += ["", "</details>", ""]

    still_open = sorted((i for i in issues if not (closed_on[i["number"]] and closed_on[i["number"]] <= as_of)), key=lambda i: i["number"])
    lines += [f"## Issues still open on {fmt(as_of)}", "", *[f"- [#{i['number']}]({REPO_URL}/issues/{i['number']}) {i['title']}" for i in still_open], ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}: {len(merged)} merged pull requests, {len(issues)} issues, sprints 1 to {last}")


if __name__ == "__main__":
    main()

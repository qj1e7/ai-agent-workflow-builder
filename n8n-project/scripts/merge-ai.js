const parsed = $('Parse Validity End & Build Reminder').first().json;
const esc = (s) => String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const notes = Array.isArray($json?.output?.notes) ? $json.output.notes : [];
const byId = new Map(notes.map((n) => [String(n.id), n]));
const rows = parsed.needsRows || [];
const covered = rows.filter((r) => byId.has(r.id));

// $json still holds the report when the AI step was skipped, and an error item when the model call failed.
const skipped = !$json?.output && $json?.hasAlerts !== undefined;
const reason = covered.length ? 'model answered' : skipped ? 'skipped, no local model running' : 'model call failed';

const confColor = (c) => ({ high: '#107c10', medium: '#8a6d00' }[String(c || '').toLowerCase()] || '#a4262c');
const td = (v, extra) => `<td style="padding:6px 10px;border-bottom:1px solid #edebe9;font-size:13px;vertical-align:top;${extra || ''}">${v}</td>`;

let section;
if (covered.length) {
  const th = ['Row', 'Why it was held back', 'Model read', 'Probable date', 'Confidence', 'Suggested next step']
    .map((h) => `<th style="text-align:left;padding:6px 10px;border-bottom:2px solid #d2d0ce;background:#f3f2f1;font-size:12px">${h}</th>`).join('');
  const tr = rows.map((r) => {
    const n = byId.get(r.id) || {};
    return `<tr>${td(esc(r.name), 'max-width:220px')}${td(esc(r.bucket))}${td(esc(n.interpretation) || '<span style="color:#a4262c">no answer</span>')}${td(esc(n.probableDate) || '-')}${td(esc(n.confidence) || '-', `color:${confColor(n.confidence)};font-weight:600`)}${td(esc(n.action) || '-')}</tr>`;
  }).join('');
  section = `<h3 style="margin:18px 0 4px;font-size:14px">Model read (local Ollama, best effort)</h3>
    <p style="margin:0 0 8px;color:#605e5c;font-size:12px">Generated by a local model from the cell text only - it cannot see the certificate. Treat probable dates as guesses to verify, never as facts.</p>
    <table style="border-collapse:collapse;width:100%"><thead><tr>${th}</tr></thead><tbody>${tr}</tbody></table>`;
} else {
  section = `<p style="margin:0 0 12px;padding:8px 10px;background:#f3f2f1;border-left:4px solid #605e5c;font-size:13px">Local model unavailable (${reason}) - these rows are listed uninterpreted below.</p>`;
}

const emailHtml = String(parsed.emailHtml).replace('<!--AI-->', section);
const emailSubject = covered.length ? `${parsed.emailSubject} · model read on ${covered.length}` : parsed.emailSubject;
const payload = JSON.parse(parsed.teamsWebhookPayload);
payload.emailHtml = emailHtml;
payload.emailSubject = emailSubject;

return [{
  json: {
    ...parsed,
    emailHtml,
    emailSubject,
    aiNotes: notes,
    aiCovered: covered.length,
    aiUsed: covered.length > 0,
    aiReason: reason,
    teamsWebhookPayload: JSON.stringify(payload),
  },
}];
